def main():
    (OUT / 'systemd').mkdir(parents=True, exist_ok=True)
    (OUT / 'env').mkdir(parents=True, exist_ok=True)
    for name, folder, port, command, rw, description in SERVICES:
        env_name = name.split('-')[0]
        user = 'vision' if name == 'vision' else 'web' if name == 'web' else 'svc'
        (OUT / 'systemd' / f'pef-{name}.service').write_text(UNIT.format(
            name=name, folder=folder, command=command, description=description, env_name=env_name, user=user,
            rw=' '.join(rw) or '/var/lib/pef/run'), encoding='utf-8', newline='\n')
    (OUT / 'systemd' / 'pef.target').write_text(
        "# Generated by scripts/generate_vm_deploy.py: `systemctl start pef.target` starts every PEF unit.\n"
        "[Unit]\nDescription=PEF (all services)\n"
        f"Wants={' '.join(f'pef-{s[0]}.service' for s in SERVICES)}\n\n[Install]\nWantedBy=multi-user.target\n",
        encoding='utf-8', newline='\n')
    (OUT / 'env' / 'common.env.example').write_text(
        "# /etc/pef/common.env (root:pef 0640). NEVER commit the real file. Values from the secret manager.\n"
        "DATABASE_URL=postgresql+psycopg://pef_app:<password>@127.0.0.1:5432/pef\n"
        "REDIS_URL=redis://:<password>@127.0.0.1:6379/0\n"
        "JWT_SECRET_KEY=<64+ random characters, identical in every service>\n"
        "JWT_ALGORITHM=HS256\n", encoding='utf-8', newline='\n')
    for env_name, lines in ENV_HINTS.items():
        (OUT / 'env' / f'{env_name}.env.example').write_text(
            f"# /etc/pef/{env_name}.env (root:pef 0640). Example only: no real value is committed.\n" + '\n'.join(lines) + '\n',
            encoding='utf-8', newline='\n')
    print('written', len(SERVICES), 'units to', OUT)


if __name__ == '__main__':
    main()
