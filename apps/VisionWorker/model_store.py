"""MS-02 / P2: the weights a session infers with are the ones Administration registered for the model pinned to
that session — resolved from a server-validated reference, verified by SHA-256, loaded once and cached.

Where weights may come from (never from a path chosen by a client):
  1. disk cache        VISION_MODEL_CACHE_DIR/<sha256>.pt  (written by this module after a verified download)
  2. bundled file      VISION_WEIGHTS_PATH, only if ITS SHA-256 equals the pinned one (no download needed)
  3. Administration storage, reference sent by the portal in a SIGNED bind:
       bucket "local" → VISION_MODEL_STORAGE_DIR/<key> (Administration's volume, mounted read-only)
       S3 (Garage)    → short-lived presigned URL generated by the portal; its host must be in
                         VISION_MODEL_FETCH_ALLOWED_HOSTS. The worker holds no S3 credentials.
     key must match ^models/[0-9a-f]{32}\\.pt$ (keys generated by the Administration server).

Every candidate is hashed before loading; a mismatch is an error, never a fallback to other weights. Loading a
.pt runs PyTorch deserialisation, so only Administration-registered artifacts identified by their SHA-256 are
ever loaded (Administration is the trusted publisher, RF-AD-08).

In memory: an LRU of loaded models keyed by SHA-256 (VISION_MODEL_CACHE_SIZE, default 2). A session keeps its
SHA-256, so frames never trigger reloads and two sessions with different models coexist.
"""
from __future__ import annotations

import hashlib
import os
import re
import tempfile
import threading
import time
from collections import OrderedDict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable
from urllib.parse import urlparse

import requests

from config import WEIGHTS_PATH

KEY_RE = re.compile(r"^models/[0-9a-f]{32}\.pt$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")

CACHE_DIR = Path(os.getenv("VISION_MODEL_CACHE_DIR", str(Path(__file__).resolve().parent / "uploads" / "model_cache")))
STORAGE_DIR = (os.getenv("VISION_MODEL_STORAGE_DIR") or "").strip()
ALLOWED_FETCH_HOSTS = {h.strip().lower() for h in (os.getenv("VISION_MODEL_FETCH_ALLOWED_HOSTS") or "").split(",")
                       if h.strip()}
CACHE_SIZE = max(1, int(os.getenv("VISION_MODEL_CACHE_SIZE", "2")))
MAX_MODEL_BYTES = int(os.getenv("VISION_MODEL_MAX_BYTES", str(4 * 1024 ** 3)))
FETCH_TIMEOUT = float(os.getenv("VISION_MODEL_FETCH_TIMEOUT", "120"))


class ModelUnavailable(Exception):
    """A pinned model cannot be served. `code` is stable for clients; `status` is the HTTP answer."""

    def __init__(self, code: str, message: str, status: int = 422):
        super().__init__(message)
        self.code, self.message, self.status = code, message, status


@dataclass(frozen=True)
class ModelSpec:
    model_id: str
    model_version: str
    sha256: str
    bucket: str | None = None
    key: str | None = None
    url: str | None = None
    class_names: dict[int, str] | None = None


def parse_spec(raw: Any) -> ModelSpec:
    if not isinstance(raw, dict):
        raise ModelUnavailable("model_required", "The bind must name the session's model")
    sha = str(raw.get("sha256") or "").strip().lower()
    if not SHA_RE.match(sha):
        raise ModelUnavailable("model_reference_invalid", "The model has no valid SHA-256 checksum")
    storage = raw.get("storage") or {}
    key = storage.get("key")
    if key is not None and not KEY_RE.match(str(key)):
        raise ModelUnavailable("model_reference_invalid", "The model storage key is not an Administration key")
    names = raw.get("class_names")
    class_names = None
    if isinstance(names, dict):
        try:
            class_names = {int(k): str(v) for k, v in names.items()}
        except (TypeError, ValueError):
            raise ModelUnavailable("model_reference_invalid", "Invalid class_names") from None
    return ModelSpec(model_id=str(raw.get("model_id") or ""), model_version=str(raw.get("model_version") or ""),
                     sha256=sha, bucket=(str(storage.get("bucket")) if storage.get("bucket") else None),
                     key=(str(key) if key else None), url=(str(storage.get("url")) if storage.get("url") else None),
                     class_names=class_names)


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


_bundled_lock = threading.Lock()
_bundled: dict[tuple, str] = {}


def bundled_sha256() -> str | None:
    """SHA-256 of VISION_WEIGHTS_PATH (cached by size/mtime), or None if absent."""
    try:
        stat = WEIGHTS_PATH.stat()
    except OSError:
        return None
    marker = (str(WEIGHTS_PATH), stat.st_size, stat.st_mtime_ns)
    with _bundled_lock:
        if marker not in _bundled:
            _bundled.clear()
            _bundled[marker] = sha256_of(WEIGHTS_PATH)
        return _bundled[marker]


def _download(spec: ModelSpec) -> Path:
    if not spec.url:
        raise ModelUnavailable("model_storage_unavailable",
                               "The model weights are in object storage but no download link was provided", 503)
    url = urlparse(spec.url)
    host = (url.netloc or "").lower()
    if url.scheme not in ("http", "https") or host not in ALLOWED_FETCH_HOSTS:
        raise ModelUnavailable("model_reference_invalid", "The model download host is not allowed")
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    digest, size = hashlib.sha256(), 0
    handle = tempfile.NamedTemporaryFile(dir=CACHE_DIR, prefix="download-", suffix=".part", delete=False)
    try:
        with handle, requests.get(spec.url, stream=True, timeout=FETCH_TIMEOUT) as response:
            if response.status_code != 200:
                raise ModelUnavailable("model_storage_unavailable",
                                       f"Object storage answered HTTP {response.status_code} for the model weights", 503)
            for chunk in response.iter_content(1024 * 1024):
                size += len(chunk)
                if size > MAX_MODEL_BYTES:
                    raise ModelUnavailable("model_weights_too_large", "The model weights exceed the allowed size")
                digest.update(chunk)
                handle.write(chunk)
    except requests.RequestException as exc:
        Path(handle.name).unlink(missing_ok=True)
        raise ModelUnavailable("model_storage_unavailable",
                               f"Object storage is not reachable: {type(exc).__name__}", 503) from None
    except ModelUnavailable:
        Path(handle.name).unlink(missing_ok=True)
        raise
    if digest.hexdigest() != spec.sha256:
        Path(handle.name).unlink(missing_ok=True)
        raise ModelUnavailable("model_checksum_mismatch",
                               "The downloaded weights do not match the model's SHA-256; they were discarded", 409)
    target = CACHE_DIR / f"{spec.sha256}.pt"
    os.replace(handle.name, target)
    return target


def resolve_weights(spec: ModelSpec) -> tuple[Path, str]:
    """Verified local path of the pinned weights and where they came from (cache|bundled|local_storage|s3)."""
    cached = CACHE_DIR / f"{spec.sha256}.pt"
    if cached.is_file():
        if sha256_of(cached) == spec.sha256:
            return cached, "cache"
        cached.unlink(missing_ok=True)          # corrupted cache entry: never used
    if bundled_sha256() == spec.sha256:
        return WEIGHTS_PATH, "bundled"
    if spec.bucket == "local":
        if not spec.key or not STORAGE_DIR:
            raise ModelUnavailable("model_storage_unavailable",
                                   "Administration's local storage is not mounted in the vision worker", 503)
        root = Path(STORAGE_DIR).resolve()
        path = (root / spec.key).resolve()
        if root not in path.parents:
            raise ModelUnavailable("model_reference_invalid", "The model storage key leaves the storage root")
        if not path.is_file():
            raise ModelUnavailable("model_weights_missing", "The model weights file is missing from storage", 404)
        if sha256_of(path) != spec.sha256:
            raise ModelUnavailable("model_checksum_mismatch",
                                   "The stored weights do not match the model's SHA-256", 409)
        return path, "local_storage"
    if spec.bucket or spec.url:
        return _download(spec), "s3"
    raise ModelUnavailable("model_weights_missing",
                           "The model has no weights file registered (upload it in Administration)", 404)


def _names(model: Any) -> dict[int, str]:
    names = getattr(model, "names", None) or {}
    if isinstance(names, (list, tuple)):
        return {i: str(n) for i, n in enumerate(names)}
    return {int(k): str(v) for k, v in dict(names).items()}


def check_classes(model: Any, spec: ModelSpec, class_ids) -> None:
    names = _names(model)
    if spec.class_names is not None and names != spec.class_names:
        raise ModelUnavailable("model_classes_incompatible",
                               "The weights' class names differ from the ones registered in Administration")
    unknown = sorted(int(c) for c in class_ids if int(c) not in names)
    if unknown:
        raise ModelUnavailable("model_classes_incompatible",
                               f"The class map uses classes the model does not have: {unknown}")


def _yolo_loader(path: Path) -> Any:
    from ultralytics import YOLO

    return YOLO(str(path))


@dataclass
class _Entry:
    model: Any
    spec: ModelSpec
    source: str
    loaded_at: float = field(default_factory=time.time)
    uses: int = 0


class ModelCache:
    def __init__(self, loader: Callable[[Path], Any] = _yolo_loader, size: int = CACHE_SIZE):
        self.loader, self.size = loader, size
        self._entries: "OrderedDict[str, _Entry]" = OrderedDict()
        self._specs: dict[str, ModelSpec] = {}
        self._lock = threading.Lock()
        self.loads = 0

    def prepare(self, spec: ModelSpec, class_ids=()) -> dict[str, Any]:
        """Resolve, verify, load (or reuse) the pinned model and check it against the class map."""
        with self._lock:
            entry = self._entries.get(spec.sha256)
            if entry is None:
                path, source = resolve_weights(spec)
                model = self.loader(path)
                check_classes(model, spec, class_ids)
                entry = _Entry(model=model, spec=spec, source=source)
                self.loads += 1
                self._entries[spec.sha256] = entry
                while len(self._entries) > self.size:
                    self._entries.popitem(last=False)
            else:
                check_classes(entry.model, spec, class_ids)
            self._entries.move_to_end(spec.sha256)
            self._specs[spec.sha256] = spec
            return {"model_id": spec.model_id, "model_version": spec.model_version, "sha256": spec.sha256,
                    "source": entry.source, "loaded": True}

    def get(self, sha256: str) -> Any:
        """The loaded model of a pinned SHA-256 (reloaded, verified again, if the LRU evicted it)."""
        with self._lock:
            entry = self._entries.get(sha256)
            if entry is not None:
                entry.uses += 1
                self._entries.move_to_end(sha256)
                return entry.model
            spec = self._specs.get(sha256)
        if spec is None:
            raise ModelUnavailable("model_not_bound", "This session's model was never prepared in the worker", 409)
        self.prepare(spec)
        return self.get(sha256)

    def loaded(self) -> list[dict[str, Any]]:
        with self._lock:
            return [{"model_id": e.spec.model_id, "model_version": e.spec.model_version, "sha256": sha,
                     "source": e.source, "uses": e.uses} for sha, e in self._entries.items()]


MODEL_CACHE = ModelCache()
